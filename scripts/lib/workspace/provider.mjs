import { createConnection } from "node:net";
import { homedir } from "node:os";
import { join } from "node:path";
import { readEnvValues, readProjectText, removeEnvNames, setEnvName, writeProjectText, } from "./dotenv.mjs";
import { deriveDeploymentReference } from "./identity.mjs";
import { workspaceExpiryAt } from "./policy.mjs";
import { describeFailure } from "./process.mjs";
export const DEPLOYMENT_ENV_NAMES = new Set([
    "CONVEX_DEPLOY_KEY",
    "CONVEX_DEPLOYMENT_TOKEN",
    "CONVEX_DEPLOYMENT",
    "VITE_CONVEX_URL",
    "CONVEX_URL",
    "CONVEX_SITE_URL",
    "NEXT_PUBLIC_CONVEX_URL",
    "EXPO_PUBLIC_CONVEX_URL",
    // `convex dev` also writes the framework-prefixed site URL (for a local
    // backend the port after the API port); it follows the selected deployment.
    "VITE_CONVEX_SITE_URL",
    "NEXT_PUBLIC_CONVEX_SITE_URL",
    "EXPO_PUBLIC_CONVEX_SITE_URL",
]);
export const PROVIDER_ENV_REMOVALS = [...DEPLOYMENT_ENV_NAMES];
/**
 * The Convex CLI looks for a package.json from its working directory upward and
 * exits without one, so every provider staging directory outside the checkout
 * gets a minimal manifest. The CLI binary still resolves from the project root.
 */
export async function stageProviderDirectory(path, { reset = true } = {}) {
    if (reset)
        await rm(path, { recursive: true, force: true });
    await mkdir(path, { recursive: true });
    await writeFile(join(path, "package.json"), `${JSON.stringify({ private: true, dependencies: { convex: "*" } })}\n`, { encoding: "utf8", mode: 0o600 });
}
function quotaHint(message) {
    return /quota/iu.test(message)
        ? `${message}. Reclaim deployments of removed worktrees with \`node scripts/workspace.mjs gc --apply\`, or prepare this worktree with \`--backend none\``
        : message;
}
async function invoke(run, request) {
    const result = await run({
        tool: "convex",
        args: request.args,
        cwd: request.cwd,
        packageRoot: request.root,
        removeEnv: PROVIDER_ENV_REMOVALS,
    });
    if (result.status !== "ok")
        throw new Error(describeFailure(request.label, result));
    return result;
}
function requireOwnedEnvironment(text) {
    if (!text.startsWith("# Generated by @appelent/dev env apply ") &&
        !text.startsWith("# Generated by `pnpm run env:apply "))
        throw new Error("Workspace backend output requires an Appelent-generated root environment file");
}
/**
 * Convex writes CONVEX_URL in the empty cloud staging directory, so name the web
 * client URL from the project's framework (stable across resumes) and from the
 * names the generated file already has.
 */
async function webClientUrlNames(root, rootEnv) {
    let dependencies = {};
    try {
        const pkg = JSON.parse((await readProjectText(root, "package.json")) || "{}");
        dependencies = { ...pkg.dependencies, ...pkg.devDependencies };
    }
    catch {
        // An unreadable package.json only loses the framework hint.
    }
    const existing = readEnvValues(rootEnv);
    return [
        ["VITE_CONVEX_URL", "vite"],
        ["NEXT_PUBLIC_CONVEX_URL", "next"],
    ]
        .filter(([name, framework]) => existing[name] !== undefined || dependencies[framework])
        .map(([name]) => name);
}
export async function prepareBackend(request) {
    const { root, identity, policy, run } = request;
    if (policy.backend.mode === "none")
        return null;
    if (!policy.backend.project)
        throw new Error("Backend project is required for an isolated workspace");
    const fallback = await readProjectText(root, ".env");
    if (removeEnvNames(fallback, DEPLOYMENT_ENV_NAMES) !== fallback)
        throw new Error("Workspace backend setup refuses deployment selectors in .env; remove them before preparing");
    let rootEnv = await readProjectText(root, policy.outputs.rootEnv);
    requireOwnedEnvironment(rootEnv);
    const clientUrlNames = await webClientUrlNames(root, rootEnv);
    rootEnv = removeEnvNames(rootEnv, DEPLOYMENT_ENV_NAMES);
    await writeProjectText(root, policy.outputs.rootEnv, rootEnv);
    const staging = policy.backend.mode === "local"
        ? root
        : join(request.isolationRoot, "provider");
    if (policy.backend.mode !== "local")
        await stageProviderDirectory(staging);
    try {
        const reference = policy.backend.mode === "cloud"
            ? `${policy.backend.project}:${deriveDeploymentReference(identity, request.editor)}`
            : `${policy.backend.project}:local`;
        const select = await run({
            tool: "convex",
            args: ["deployment", "select", reference],
            cwd: staging,
            packageRoot: root,
            removeEnv: PROVIDER_ENV_REMOVALS,
        });
        let created = false;
        if (select.status === "not-found") {
            await request.checkpoint({
                kind: "convex-deployment",
                id: reference,
                owned: true,
                status: "retained",
                cleanup: policy.backend.mode === "cloud" ? "expiry" : "release",
                expiresAt: policy.backend.mode === "cloud"
                    ? (workspaceExpiryAt(policy.backend.expiration, request.now) ??
                        undefined)
                    : undefined,
                metadata: {
                    mode: policy.backend.mode,
                    expiration: policy.backend.expiration,
                },
            });
            const args = policy.backend.mode === "cloud"
                ? [
                    "deployment",
                    "create",
                    reference,
                    "--select",
                    "--type",
                    "dev",
                    "--expiration",
                    policy.backend.expiration,
                ]
                : ["deployment", "create", reference, "--select"];
            try {
                await invoke(run, {
                    root,
                    cwd: staging,
                    args,
                    label: "Backend creation",
                });
            }
            catch (error) {
                // A quota refusal happens before anything is created, so the intent
                // recorded above owns nothing. Mark it absent, so clean and gc can
                // finish instead of waiting days for an expiry that never comes.
                if (/quota/iu.test(error.message))
                    await request.checkpoint({
                        kind: "convex-deployment",
                        id: reference,
                        owned: true,
                        status: "absent",
                        cleanup: policy.backend.mode === "cloud" ? "expiry" : "release",
                        metadata: {
                            mode: policy.backend.mode,
                            expiration: policy.backend.expiration,
                        },
                    });
                throw new Error(quotaHint(error.message));
            }
            created = true;
            await request.checkpoint({
                kind: "convex-deployment",
                id: reference,
                owned: true,
                status: "active",
                cleanup: policy.backend.mode === "cloud" ? "expiry" : "release",
                expiresAt: policy.backend.mode === "cloud"
                    ? (workspaceExpiryAt(policy.backend.expiration, request.now) ??
                        undefined)
                    : undefined,
                metadata: {
                    mode: policy.backend.mode,
                    expiration: policy.backend.expiration,
                },
            });
        }
        else if (select.status !== "ok") {
            throw new Error(`${describeFailure("Backend lookup", select)}; refusing to create`);
        }
        const selected = readEnvValues(await readProjectText(staging, ".env.local"));
        const publicUrl = selected.VITE_CONVEX_URL ?? selected.CONVEX_URL;
        const deploymentName = selected.CONVEX_DEPLOYMENT;
        if (!publicUrl || !deploymentName)
            throw new Error("Selected backend did not provide client outputs");
        let publicHostname;
        try {
            publicHostname = new URL(publicUrl).hostname;
        }
        catch {
            throw new Error("Selected backend wrote an invalid client URL");
        }
        for (const name of [
            "CONVEX_DEPLOYMENT",
            "VITE_CONVEX_URL",
            "CONVEX_URL",
            "CONVEX_SITE_URL",
        ])
            if (selected[name] !== undefined)
                rootEnv = setEnvName(rootEnv, name, selected[name] ?? "");
        for (const name of clientUrlNames)
            rootEnv = setEnvName(rootEnv, name, publicUrl);
        await writeProjectText(root, policy.outputs.rootEnv, rootEnv);
        const resource = {
            kind: "convex-deployment",
            id: reference,
            owned: created || request.existing?.owned === true,
            status: "active",
            cleanup: policy.backend.mode === "cloud" ? "expiry" : "release",
            expiresAt: request.existing?.expiresAt ??
                (policy.backend.mode === "cloud"
                    ? (workspaceExpiryAt(policy.backend.expiration, request.now) ??
                        undefined)
                    : undefined),
            metadata: {
                mode: policy.backend.mode,
                deploymentName,
                expiration: policy.backend.expiration,
            },
        };
        await request.checkpoint(resource);
        return {
            reference,
            publicUrl,
            publicHostname,
            resource,
            operation: {
                action: created ? "write" : "reuse",
                target: `convex:${reference}`,
                detail: created
                    ? "created isolated backend"
                    : "selected existing backend",
            },
        };
    }
    finally {
        if (policy.backend.mode === "cloud")
            await rm(staging, { recursive: true, force: true }).catch(() => undefined);
    }
}
export async function createScopedCredential(request) {
    const staging = join(request.isolationRoot, "provider-token");
    await stageProviderDirectory(staging);
    try {
        const tokenName = `appelent-${request.identity.id}`;
        const resource = {
            kind: "convex-token",
            id: tokenName,
            owned: true,
            status: "retained",
            cleanup: "delete",
            metadata: { deployment: request.reference },
        };
        await request.checkpoint(resource);
        const result = await invoke(request.run, {
            root: request.root,
            cwd: staging,
            args: [
                "deployment",
                "token",
                "create",
                tokenName,
                "--deployment",
                request.reference,
            ],
            label: "Scoped credential creation",
        });
        const token = /(?:^|\n)((?:dev|prod|preview):[^|\r\n]+\|[^\s\r\n]+)(?:\r?\n|$)/u.exec(result.stdout)?.[1];
        if (!token)
            throw new Error("Scoped credential was created but its value was not captured");
        resource.status = "active";
        await request.checkpoint(resource);
        const current = await readProjectText(request.root, request.policy.outputs.rootEnv);
        requireOwnedEnvironment(current);
        await writeProjectText(request.root, request.policy.outputs.rootEnv, setEnvName(current, "CONVEX_DEPLOY_KEY", token));
        return {
            resource,
            operation: {
                action: "write",
                target: `convex-token:${tokenName}`,
                detail: "created scoped credential",
            },
        };
    }
    finally {
        await rm(staging, { recursive: true, force: true }).catch(() => undefined);
    }
}
export async function pushBackend(root, policy, run) {
    const values = readEnvValues(await readProjectText(root, policy.outputs.rootEnv));
    const key = values.CONVEX_DEPLOY_KEY;
    const selected = values.CONVEX_DEPLOYMENT;
    if (!key || !selected || !key.startsWith(`${selected}|`))
        throw new Error("Scoped credential does not match the selected backend");
    await invoke(run, {
        root,
        cwd: root,
        args: ["dev", "--once", "--env-file", policy.outputs.rootEnv],
        label: "Backend push",
    });
}
export async function writeClientOutputs(root, policy, publicUrl) {
    if (!publicUrl || !policy.outputs.mobileEnv)
        return [];
    const current = await readProjectText(root, policy.outputs.mobileEnv);
    if (current &&
        !current.startsWith("# Generated by @appelent/dev env apply ") &&
        !current.startsWith("# Generated by `pnpm run env:apply "))
        throw new Error("Workspace mobile output requires an Appelent-generated environment file");
    await writeProjectText(root, policy.outputs.mobileEnv, setEnvName(current, policy.outputs.mobileUrlName, publicUrl));
    return [
        {
            action: "write",
            target: policy.outputs.mobileEnv,
            detail: `${policy.outputs.mobileUrlName} follows selected backend`,
        },
    ];
}
export async function cleanupProviderResource(packageRoot, isolationRoot, resource, run, now = new Date(), platform = {}) {
    if (!resource.owned ||
        resource.status === "removed" ||
        resource.status === "absent")
        return resource;
    if (resource.kind === "convex-token") {
        const deployment = String(resource.metadata?.deployment ?? "");
        if (!deployment)
            return { ...resource, status: "inaccessible" };
        await stageProviderDirectory(isolationRoot, { reset: false });
        const result = await run({
            tool: "convex",
            args: [
                "deployment",
                "token",
                "delete",
                resource.id,
                "--deployment",
                deployment,
            ],
            cwd: isolationRoot,
            packageRoot,
            removeEnv: PROVIDER_ENV_REMOVALS,
        });
        if (result.status === "ok" || result.status === "not-found")
            return {
                ...resource,
                status: result.status === "ok" ? "removed" : "absent",
            };
        return { ...resource, status: "inaccessible" };
    }
    if (resource.kind === "convex-deployment") {
        // A local deployment is shared (project-wide) state on this machine, not a
        // lease this workspace created: release the ledger entry and leave the
        // deployment and any backend another worktree runs untouched.
        if (resource.cleanup === "release")
            return { ...resource, status: "removed" };
        if (resource.cleanup !== "expiry")
            return { ...resource, status: "retained" };
        const expired = Boolean(resource.expiresAt) &&
            new Date(resource.expiresAt).getTime() <= now.getTime();
        const recordedName = String(resource.metadata?.deploymentName ?? "");
        // Without a recorded deployment name there is nothing to delete safely;
        // an unexpired deployment then waits for its expiry as before.
        if (!expired && !recordedName)
            return { ...resource, status: "pending-expiry" };
        await stageProviderDirectory(isolationRoot);
        const result = await run({
            tool: "convex",
            args: ["deployment", "select", resource.id],
            cwd: isolationRoot,
            packageRoot,
            removeEnv: PROVIDER_ENV_REMOVALS,
        });
        if (result.status === "not-found")
            return { ...resource, status: "absent" };
        if (result.status !== "ok")
            return { ...resource, status: expired ? "inaccessible" : "pending-expiry" };
        // Delete only when the reference still resolves to the deployment this
        // workspace created, so quota is freed when the worktree goes away.
        const selected = readEnvValues(await readProjectText(isolationRoot, ".env.local")).CONVEX_DEPLOYMENT;
        if (recordedName.startsWith("dev:") && selected === recordedName) {
            const deleted = await deleteOwnedCloudDeployment({
                name: recordedName.slice("dev:".length),
                reference: resource.id.split(":").slice(2).join(":"),
                ...platform,
            });
            if (deleted === "removed" || deleted === "absent")
                return { ...resource, status: deleted };
            if (deleted === "refused")
                return { ...resource, status: "inaccessible" };
        }
        return { ...resource, status: "pending-expiry" };
    }
    if (resource.kind === "port")
        return { ...resource, status: "removed" };
    if (resource.kind === "process") {
        const pid = Number(resource.metadata?.pid);
        if (!Number.isSafeInteger(pid) || pid <= 0)
            return { ...resource, status: "inaccessible" };
        try {
            process.kill(pid, 0);
            return { ...resource, status: "inaccessible" };
        }
        catch (error) {
            return error.code === "ESRCH"
                ? { ...resource, status: "absent" }
                : { ...resource, status: "inaccessible" };
        }
    }
    return resource;
}
async function readAccessToken(environ, home) {
    if (environ.CONVEX_OVERRIDE_ACCESS_TOKEN)
        return environ.CONVEX_OVERRIDE_ACCESS_TOKEN;
    try {
        const parsed = JSON.parse(await readFile(join(home, ".convex", "config.json"), "utf8"));
        return typeof parsed.accessToken === "string" && parsed.accessToken
            ? parsed.accessToken
            : null;
    }
    catch {
        return null;
    }
}
/**
 * Deletes a workspace-owned cloud dev deployment through the Convex Management
 * API with the signed-in CLI's access token (the CLI has no delete command).
 * Refuses anything that is not a non-default dev deployment with the recorded
 * reference. Returns removed, absent, refused, or unavailable (try again later
 * or let it expire).
 */
export async function deleteOwnedCloudDeployment({ name, reference, fetch: fetchImpl = globalThis.fetch, environ = process.env, home = homedir(), timeoutMs = 30_000, }) {
    if (!/^[a-z0-9-]+$/u.test(name) || !reference.startsWith("dev/"))
        return "refused";
    const token = await readAccessToken(environ, home);
    if (!token || typeof fetchImpl !== "function")
        return "unavailable";
    const host = (environ.CONVEX_PROVISION_HOST ?? "https://api.convex.dev").replace(/\/+$/u, "");
    if (!host.startsWith("https://") && !/^http:\/\/(?:127\.0\.0\.1|localhost)(?::\d+)?$/u.test(host))
        return "unavailable";
    const base = `${host}/v1/deployments/${encodeURIComponent(name)}`;
    const headers = { Authorization: `Bearer ${token}` };
    try {
        const lookup = await fetchImpl(base, {
            headers,
            signal: AbortSignal.timeout(timeoutMs),
        });
        if (lookup.status === 404)
            return "absent";
        if (!lookup.ok)
            return "unavailable";
        const details = await lookup.json().catch(() => null);
        // Every ownership field must be present and match; a response that
        // cannot establish them keeps the deployment until it expires.
        if (!details ||
            details.name !== name ||
            details.deploymentType !== "dev" ||
            details.reference !== reference ||
            details.isDefault !== false ||
            (details.kind !== undefined && details.kind !== "cloud"))
            return "refused";
        const removal = await fetchImpl(`${base}/delete`, {
            method: "POST",
            headers,
            signal: AbortSignal.timeout(timeoutMs),
        });
        if (removal.status === 404)
            return "absent";
        return removal.ok ? "removed" : "unavailable";
    }
    catch {
        return "unavailable";
    }
}

function isListening(host, port, timeoutMs) {
    return new Promise((done) => {
        const socket = createConnection({ host, port });
        const finish = (value) => {
            socket.destroy();
            done(value);
        };
        socket.setTimeout(timeoutMs, () => finish(false));
        socket.once("connect", () => finish(true));
        socket.once("error", () => finish(false));
    });
}
function listeningProcess(port, timeoutMs) {
    return new Promise((done) => {
        if (process.platform === "win32")
            return done(null);
        execFile("lsof", ["-nP", `-iTCP:${port}`, "-sTCP:LISTEN", "-Fpc"], { timeout: timeoutMs }, (error, stdout) => {
            if (error && !stdout)
                return done(null);
            const pid = /^p(\d+)$/mu.exec(stdout)?.[1];
            const command = /^c(.+)$/mu.exec(stdout)?.[1];
            done(pid ? { pid: Number(pid), command: command ?? "unknown" } : null);
        });
    });
}
/**
 * Reports whether anything listens on the selected local backend URL. Local-mode
 * prepare applies backend values only when it does: the Convex CLI never starts a
 * local backend for `env set`, and prepare does not start one either.
 */
export async function localBackendListening(publicUrl, { probe = isListening, timeoutMs = 2_000 } = {}) {
    let url;
    try {
        url = new URL(publicUrl ?? "");
    }
    catch {
        return false;
    }
    const host = url.hostname || "127.0.0.1";
    const port = Number(url.port || (url.protocol === "https:" ? 443 : 80));
    return probe(host, port, timeoutMs);
}
/**
 * Explains why routing values into a local Convex deployment failed. The Convex
 * CLI never starts a local backend for `env set`, and picks the first free port
 * from 3210, so the usual causes are a backend that is not running or a port
 * that another worktree's backend holds. Names the port and what holds it.
 */
export async function diagnoseLocalBackend(publicUrl, { probe = isListening, holder = listeningProcess, timeoutMs = 2_000, } = {}) {
    let url;
    try {
        url = new URL(publicUrl ?? "");
    }
    catch {
        return "the selected local backend URL is missing or invalid";
    }
    const host = url.hostname || "127.0.0.1";
    const port = Number(url.port || (url.protocol === "https:" ? 443 : 80));
    if (!(await probe(host, port, timeoutMs)))
        return (`no local Convex backend is listening on ${host}:${port}; start this worktree's backend ` +
            "(for example `pnpm exec convex dev`; it takes the next free port when another one holds it) and run prepare again");
    const owner = await holder(port, timeoutMs);
    const who = owner
        ? `${owner.command} (pid ${owner.pid})`
        : "another process";
    return (`${host}:${port} is held by ${who}; if that is another worktree's backend this ` +
        "worktree cannot use the port: stop it, or start this worktree's backend with " +
        "`pnpm exec convex dev` (it takes the next free port) and run prepare again");
}
